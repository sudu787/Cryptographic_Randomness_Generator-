"""Per-browser-session state shared between pages, and access to the experiment history.

Only metadata and summaries are kept in session state. Generated bytes from the Randomness Lab
stay in memory for the current page and are never written anywhere.
"""

from __future__ import annotations

from pathlib import Path

import streamlit as st

from entropylens.monitoring.alerts import Alert, SourceStatus
from entropylens.storage.history import HISTORY_FILE, ExperimentHistory, SyncReport

DEFAULT_RESULTS_DIR = Path("experiments") / "results"
MAX_RECENT_ALERTS = 8


def results_dir() -> Path:
    """Results directory (overridable in session state, which the tests use)."""
    return Path(st.session_state.get("results_dir", DEFAULT_RESULTS_DIR))


def history() -> ExperimentHistory:
    """The SQLite history index of the results directory."""
    return ExperimentHistory(results_dir() / HISTORY_FILE)


def synced_history() -> tuple[ExperimentHistory, SyncReport]:
    """The history after indexing any new result files."""
    index = history()
    directory = results_dir()
    report = index.sync(directory) if directory.is_dir() else SyncReport()
    return index, report


def record_monitor_result(status: SourceStatus, samples: int, alerts: list[Alert]) -> None:
    """Remember the latest monitor outcome and its alerts for the Overview page."""
    st.session_state["monitor_status"] = status
    st.session_state["monitor_samples"] = samples
    recent: list[Alert] = st.session_state.get("recent_alerts", [])
    st.session_state["recent_alerts"] = (list(alerts) + recent)[:MAX_RECENT_ALERTS]


def monitor_status() -> tuple[SourceStatus | None, int]:
    """Latest monitor status in this browser session, and samples examined."""
    return st.session_state.get("monitor_status"), int(st.session_state.get("monitor_samples", 0))


def recent_alerts() -> list[Alert]:
    """Most recent alerts in this browser session, newest first."""
    return list(st.session_state.get("recent_alerts", []))
